// ---- 构建扁平词库 ----
// 去重仅限同一库内同一词性，跨库/跨词性的同名词允许共存
function dedupSplit(str) {
  if (!str) return []
  const seen = new Set()
  return str.split(/[,，]/).map(s => s.trim()).filter(s => {
    if (!s || seen.has(s)) return false
    seen.add(s)
    return true
  })
}

function buildLib(lib) {
  const result = []
  const absN = new Set((lib.abstractN || '').split(/[,，]/).map(s => s.trim()).filter(Boolean))
  const absV = new Set((lib.abstractV || '').split(/[,，]/).map(s => s.trim()).filter(Boolean))
  const conN = new Set((lib.concreteN || '').split(/[,，]/).map(s => s.trim()).filter(Boolean))
  const conV = new Set((lib.concreteV || '').split(/[,，]/).map(s => s.trim()).filter(Boolean))

  const addBatch = (str, pos) => {
    for (const w of dedupSplit(str)) {
      let physical = (pos === 'A' || pos === 'C') ? 'abstract' : lib.defaultPhysical
      if (pos === 'N') {
        if (absN.has(w)) physical = 'abstract'
        if (conN.has(w)) physical = 'concrete'
      }
      if (pos === 'V') {
        if (absV.has(w)) physical = 'abstract'
        if (conV.has(w)) physical = 'concrete'
      }
      result.push(mk(w, pos, lib.tone, physical))
    }
  }
  addBatch(lib.nouns, 'N')
  addBatch(lib.verbs, 'V')
  addBatch(lib.adjs, 'A')
  addBatch(lib.funcs, 'C')
  return result
}

export const deckData = libs.flatMap(buildLib)

